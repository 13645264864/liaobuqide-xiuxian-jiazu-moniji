FROM public.fc_cities ct JOIN public.fc_states st ON st.id=ct.state_id CROSS JOIN public.fc_world_rooms r WHERE ct.id>1 AND r.city_id=1 AND r.family_id IS NULL AND r.id<>'10000000-0000-0000-0000-000000000001' AND r.id::text NOT BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022';
INSERT INTO public.fc_world_cells(id,room_id,x,y,terrain) SELECT md5('city:'||r.city_id||':cell:'||c.id)::uuid,r.id,c.x,c.y,c.terrain FROM public.fc_world_rooms r JOIN public.fc_world_cells c ON c.room_id=r.template_id WHERE r.city_id>1 AND r.family_id IS NULL;
INSERT INTO public.fc_world_exits SELECT md5('city:'||r.city_id||':cell:'||e.from_cell)::uuid,e.direction,md5('city:'||r.city_id||':cell:'||e.to_cell)::uuid FROM public.fc_world_rooms r JOIN public.fc_world_cells c ON c.room_id=r.template_id JOIN public.fc_world_exits e ON e.from_cell=c.id JOIN public.fc_world_cells dest ON dest.id=e.to_cell JOIN public.fc_world_rooms dr ON dr.id=dest.room_id WHERE r.city_id>1 AND r.family_id IS NULL AND dr.family_id IS NULL AND dr.id<>'10000000-0000-0000-0000-000000000001' AND dr.id::text NOT BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022';
CREATE OR REPLACE FUNCTION public.fc_get_world_state() RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_uid text:=public.fc_require_uid(); v_me public.fc_characters; v_pos public.fc_character_positions; v_cell public.fc_world_cells; v_room public.fc_world_rooms; v_home uuid;
BEGIN
 SELECT * INTO v_me FROM public.fc_characters WHERE owner_id=v_uid; IF v_me.id IS NULL THEN RAISE EXCEPTION '请先入世'; END IF;
 v_home:=public.fc_ensure_family_home(v_me.family_id);
 SELECT * INTO v_pos FROM public.fc_character_positions WHERE character_id=v_me.id;
 IF EXISTS(SELECT 1 FROM public.fc_city_journeys WHERE character_id=v_me.id AND arrives_at<=now()) THEN
 SELECT c.* INTO v_cell FROM public.fc_city_journeys j JOIN public.fc_world_rooms r ON r.city_id=j.destination AND (r.template_id='10000000-0000-0000-0000-000000000006' OR r.id='10000000-0000-0000-0000-000000000006') JOIN public.fc_world_cells c ON c.room_id=r.id AND c.x=0 AND c.y=0 WHERE j.character_id=v_me.id;
 UPDATE public.fc_character_positions SET cell_id=v_cell.id WHERE character_id=v_me.id;
 DELETE FROM public.fc_city_journeys WHERE character_id=v_me.id;
 SELECT * INTO v_pos FROM public.fc_character_positions WHERE character_id=v_me.id;
 END IF;
 IF v_pos.cell_id IS NULL THEN
  SELECT * INTO v_cell FROM public.fc_world_cells WHERE room_id=v_home AND x=0 AND y=0;
  INSERT INTO public.fc_character_positions(character_id,cell_id) VALUES(v_me.id,v_cell.id) ON CONFLICT (character_id) DO NOTHING;
  SELECT * INTO v_pos FROM public.fc_character_positions WHERE character_id=v_me.id;
 ELSE
  SELECT * INTO v_cell FROM public.fc_world_cells WHERE id=v_pos.cell_id;
 END IF;
 IF EXISTS(SELECT 1 FROM public.fc_world_rooms r WHERE r.id=v_cell.room_id AND r.family_id IS NULL AND (r.id='10000000-0000-0000-0000-000000000001' OR r.id::text BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022')) THEN
 SELECT * INTO v_cell FROM public.fc_world_cells WHERE id=md5(v_me.family_id::text||':cell:'||v_cell.id::text)::uuid;
 UPDATE public.fc_character_positions SET cell_id=v_cell.id WHERE character_id=v_me.id;
 END IF;
 UPDATE public.fc_character_positions SET updated_at=now() WHERE character_id=v_me.id;
 SELECT * INTO v_room FROM public.fc_world_rooms WHERE id=v_cell.room_id;
 RETURN jsonb_build_object('atlas',jsonb_build_object('states',(SELECT jsonb_agg(to_jsonb(s)) FROM public.fc_states s),'cities',(SELECT jsonb_agg(to_jsonb(c)) FROM public.fc_cities c),'roads',(SELECT jsonb_agg(to_jsonb(e)) FROM public.fc_city_roads e)),'journey',(SELECT to_jsonb(j) FROM public.fc_city_journeys j WHERE j.character_id=v_me.id),'room',to_jsonb(v_room),'cell',to_jsonb(v_cell),'cells',(SELECT jsonb_agg(to_jsonb(t) ORDER BY t.y,t.x) FROM public.fc_world_cells t WHERE t.room_id=v_room.id),'exits',coalesce((SELECT jsonb_agg(jsonb_build_object('from_cell',e.from_cell,'x',c.x,'y',c.y,'direction',e.direction,'to_room',CASE WHEN r.id='10000000-0000-0000-0000-000000000001' THEN (SELECT name FROM public.fc_world_rooms WHERE id=v_home) ELSE r.name END)) FROM public.fc_world_exits e JOIN public.fc_world_cells c ON c.id=e.from_cell JOIN public.fc_world_cells dest ON dest.id=e.to_cell JOIN public.fc_world_rooms r ON r.id=dest.room_id WHERE c.room_id=v_room.id),'[]'::jsonb),'navigation',jsonb_build_object('cells',(SELECT jsonb_agg(to_jsonb(c)) FROM public.fc_world_cells c JOIN public.fc_world_rooms r ON r.id=c.room_id WHERE (r.family_id=v_me.family_id AND r.city_id=v_room.city_id OR (r.city_id=v_room.city_id AND r.family_id IS NULL AND r.id<>'10000000-0000-0000-0000-000000000001' AND r.id::text NOT BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022'))),'edges',(SELECT jsonb_agg(jsonb_build_object('from',c.id,'to',n.id,'direction',d.direction)) FROM public.fc_world_cells c JOIN public.fc_world_rooms r ON r.id=c.room_id CROSS JOIN (VALUES ('north'),('south'),('east'),('west')) d(direction) JOIN public.fc_world_cells n ON n.id=CASE WHEN c.room_id='10000000-0000-0000-0000-000000000005' AND c.x=0 AND c.y=-1 AND d.direction='north' THEN (SELECT id FROM public.fc_world_cells WHERE room_id=v_home AND x=0 AND y=1) ELSE public.fc_world_next_cell(c.id,d.direction) END WHERE (r.family_id=v_me.family_id AND r.city_id=v_room.city_id OR (r.city_id=v_room.city_id AND r.family_id IS NULL AND r.id<>'10000000-0000-0000-0000-000000000001' AND r.id::text NOT BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022')) AND EXISTS(SELECT 1 FROM public.fc_world_rooms nr WHERE nr.id=n.room_id AND (nr.family_id IS NULL OR nr.family_id=v_me.family_id)))),'map_rooms',(SELECT jsonb_agg(to_jsonb(r)) FROM public.fc_world_rooms r WHERE (r.family_id=v_me.family_id AND r.city_id=v_room.city_id OR (r.city_id=v_room.city_id AND r.family_id IS NULL AND r.id<>'10000000-0000-0000-0000-000000000001' AND r.id::text NOT BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022'))),'nearby',coalesce((SELECT jsonb_agg(jsonb_build_object('id',c.id,'name',c.display_name,'title',c.title)) FROM public.fc_character_positions p JOIN public.fc_characters c ON c.id=p.character_id WHERE p.cell_id=v_cell.id AND c.id<>v_me.id AND p.updated_at>now()-interval '90 seconds'),'[]'::jsonb));
END $$;
GRANT EXECUTE ON FUNCTION public.fc_get_world_state() TO authenticated;
CREATE OR REPLACE FUNCTION public.fc_ensure_family_home(p_family uuid) RETURNS uuid LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_name text; v_home uuid:=md5(p_family::text||':room:10000000-0000-0000-0000-000000000001')::uuid;
BEGIN
 SELECT name INTO v_name FROM public.fc_families WHERE id=p_family; IF v_name IS NULL THEN RAISE EXCEPTION '宗族不存在'; END IF;
 PERFORM pg_advisory_xact_lock(hashtext(p_family::text));
 INSERT INTO public.fc_world_rooms(id,state_name,city_name,name,kind,danger,encounter_rate,description,family_id,template_id)
 SELECT md5(p_family::text||':room:'||id::text)::uuid,state_name,city_name,CASE WHEN id='10000000-0000-0000-0000-000000000001' THEN v_name||'宅邸' ELSE name END,kind,danger,encounter_rate,description,p_family,id FROM public.fc_world_rooms WHERE family_id IS NULL AND (id='10000000-0000-0000-0000-000000000001' OR id::text BETWEEN '10000000-0000-0000-0000-000000000010' AND '10000000-0000-0000-0000-000000000022') ON CONFLICT DO NOTHING;
 UPDATE public.fc_world_rooms SET name=v_name||'宅邸',description='属于'||v_name||'的宗族宅邸。族长与族人都在这里入世，南侧通向城中府前街，北侧通向本族内院。' WHERE id=v_home;
 INSERT INTO public.fc_world_cells(id,room_id,x,y,terrain) SELECT md5(p_family::text||':cell:'||c.id::text)::uuid,r.id,c.x,c.y,c.terrain FROM public.fc_world_rooms r JOIN public.fc_world_cells c ON c.room_id=r.template_id WHERE r.family_id=p_family ON CONFLICT DO NOTHING;
 INSERT INTO public.fc_world_exits(from_cell,direction,to_cell)
 SELECT md5(p_family::text||':cell:'||e.from_cell::text)::uuid,e.direction,CASE WHEN dest.room_id='10000000-0000-0000-0000-000000000005' THEN e.to_cell ELSE md5(p_family::text||':cell:'||e.to_cell::text)::uuid END
 FROM public.fc_world_exits e JOIN public.fc_world_cells src ON src.id=e.from_cell JOIN public.fc_world_rooms r ON r.template_id=src.room_id AND r.family_id=p_family JOIN public.fc_world_cells dest ON dest.id=e.to_cell ON CONFLICT DO NOTHING;
 UPDATE public.fc_world_rooms SET city_id=coalesce((SELECT city_id FROM public.fc_families WHERE id=p_family),1) WHERE family_id=p_family;
 RETURN v_home;
END $$;
REVOKE ALL ON FUNCTION public.fc_ensure_family_home(uuid) FROM PUBLIC;
CREATE FUNCTION public.fc_start_city_journey(p_destination integer,p_mode text DEFAULT 'walk') RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_me public.fc_characters; v_city integer; v_distance numeric; v_seconds integer;
BEGIN
 SELECT * INTO v_me FROM public.fc_characters WHERE owner_id=public.fc_require_uid() FOR UPDATE;
 IF v_me.id IS NULL THEN RAISE EXCEPTION '请先入世'; END IF;
 PERFORM public.fc_get_world_state();
 IF EXISTS(SELECT 1 FROM public.fc_city_journeys WHERE character_id=v_me.id) THEN RAISE EXCEPTION '正在城际旅行'; END IF;
 SELECT r.city_id INTO v_city FROM public.fc_character_positions p JOIN public.fc_world_cells c ON c.id=p.cell_id JOIN public.fc_world_rooms r ON r.id=c.room_id WHERE p.character_id=v_me.id;
 SELECT distance INTO v_distance FROM public.fc_city_roads WHERE a=least(v_city,p_destination) AND b=greatest(v_city,p_destination);
 IF v_distance IS NULL THEN RAISE EXCEPTION '只能沿道路前往相邻城池'; END IF;
 IF p_mode<>'walk' THEN RAISE EXCEPTION '马车、飞剑、云舟需接入对应服务或器物后使用'; END IF;
 v_seconds:=ceil(v_distance*600);
 PERFORM public.fc_claim_cultivation();
 INSERT INTO public.fc_city_journeys VALUES(v_me.id,p_destination,now(),now()+make_interval(secs=>v_seconds),p_mode);
 RETURN public.fc_get_world_state();
END $$;
REVOKE ALL ON FUNCTION public.fc_start_city_journey(integer,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fc_start_city_journey(integer,text) TO authenticated;
CREATE OR REPLACE FUNCTION public.fc_move_world(p_direction text) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_uid text:=public.fc_require_uid(); v_me public.fc_characters; v_pos public.fc_character_positions; v_cell public.fc_world_cells; v_next public.fc_world_cells; dx integer:=0; dy integer:=0;
BEGIN
 SELECT * INTO v_me FROM public.fc_characters WHERE owner_id=v_uid; IF v_me.id IS NULL THEN RAISE EXCEPTION '请先入世'; END IF;
 PERFORM public.fc_get_world_state(); SELECT * INTO v_pos FROM public.fc_character_positions WHERE character_id=v_me.id FOR UPDATE; IF v_pos.cell_id IS NULL THEN PERFORM public.fc_get_world_state(); SELECT * INTO v_pos FROM public.fc_character_positions WHERE character_id=v_me.id; END IF;
 IF EXISTS(SELECT 1 FROM public.fc_city_journeys WHERE character_id=v_me.id) THEN RAISE EXCEPTION '正在城际旅行，抵达前不能移动'; END IF;
 SELECT * INTO v_cell FROM public.fc_world_cells WHERE id=v_pos.cell_id;
 IF p_direction='north' THEN dy:=-1; ELSIF p_direction='south' THEN dy:=1; ELSIF p_direction='west' THEN dx:=-1; ELSIF p_direction='east' THEN dx:=1; ELSE RAISE EXCEPTION '方向无效'; END IF;
 SELECT n.* INTO v_next FROM public.fc_world_cells n WHERE n.id=CASE WHEN v_cell.room_id='10000000-0000-0000-0000-000000000005' AND v_cell.x=0 AND v_cell.y=-1 AND p_direction='north' THEN (SELECT c.id FROM public.fc_world_cells c JOIN public.fc_world_rooms r ON r.id=c.room_id WHERE r.family_id=v_me.family_id AND r.template_id='10000000-0000-0000-0000-000000000001' AND c.x=0 AND c.y=1) ELSE public.fc_world_next_cell(v_cell.id,p_direction) END;
 IF v_next.id IS NULL THEN RAISE EXCEPTION '这里没有可通行的道路'; END IF;
 PERFORM public.fc_claim_cultivation();
 UPDATE public.fc_character_positions SET cell_id=v_next.id,updated_at=now() WHERE character_id=v_me.id;
 RETURN public.fc_get_world_state();
END $$;
GRANT EXECUTE ON FUNCTION public.fc_get_world_state(),public.fc_move_world(text) TO authenticated;
